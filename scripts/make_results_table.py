"""Render benchmark/RESULTS.md from benchmark/results/*.json."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from shora.benchmark import load_split  # noqa: E402

R = ROOT / "benchmark" / "results"


def j(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def preds(name):
    p = R / name
    return {json.loads(l)["id"]: json.loads(l)["pred"] for l in p.read_text().splitlines()} if p.exists() else {}


def pct(x):
    return "—" if x is None else f"{x * 100:.1f}"


def row(res, extra=""):
    pl = res["per_language_macro_f1"]
    return (f"| {res['model']}{extra} | {res['n']} | {pct(res['accuracy'])} | {pct(res['macro_f1'])} | "
            + " | ".join(pct(pl.get(l)) for l in ["en", "pcm", "yo", "ig", "ha"]) + " |")


HEAD = ("| Model | n | Accuracy | Macro-F1 | EN | PCM | YO | IG | HA |\n"
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|")


def main():
    lines = ["# NaijaScamBench v0.1 results", "",
             "All numbers in %. Per-language columns are macro-F1 (scam vs legit). "
             "Generated by `scripts/make_results_table.py`.", "",
             "## Test split (365 held-out synthetic messages)", "", HEAD]
    for f in ["rules.json", "tfidf_logreg.json", "afro_xlmr_mini.json"]:
        if j(f):
            lines.append(row(j(f)))
    llm = j("llm_openai-gpt-oss-120b_test.json") or j("llm_openai-gpt-oss-120b_test_partial.json")
    if llm:
        lines.append(row(llm, " †" if llm.get("partial") else ""))
    tf = j("tfidf_logreg.json")
    if tf:
        lines += ["", f"TF-IDF + LogReg also predicts the 17-way `scam_type`: accuracy {pct(tf['scam_type_accuracy'])}, "
                      f"macro-F1 {pct(tf['scam_type_macro_f1'])}; ~{tf['ms_per_message_cpu']} ms/message on CPU."]
    lines += ["", "## Challenge set (40 hand-written, out-of-distribution messages)", "", HEAD]
    for f in ["rules_challenge.json", "tfidf_logreg_challenge.json", "afro_xlmr_mini_challenge.json"]:
        if j(f):
            lines.append(row(j(f)))
    llmc = j("llm_openai-gpt-oss-120b_challenge.json") or j("llm_openai-gpt-oss-120b_challenge_partial.json")
    if llmc:
        lines.append(row(llmc, " †" if llmc.get("partial") else ""))
    # scam recall on the challenge scams that every model scored
    ch = load_split("challenge")
    scams = [r for r in ch if r["label"] == "scam"]
    lp = preds("llm_openai-gpt-oss-120b_challenge_predictions.jsonl")
    common = [r for r in scams if r["id"] in lp] if lp else scams
    lines += ["", f"**Scam recall on the {len(common)} challenge scams** (the metric that matters most for users):", ""]
    for name, f in [("TF-IDF + LogReg", "tfidf_logreg_challenge_predictions.jsonl"),
                    ("afro-xlmr-mini fine-tuned", "afro_xlmr_mini_challenge_predictions.jsonl"),
                    ("Zero-shot gpt-oss-120b", "llm_openai-gpt-oss-120b_challenge_predictions.jsonl")]:
        p = preds(f)
        if p:
            hit = sum(p.get(r["id"]) == "scam" for r in common)
            lines.append(f"- {name}: {hit}/{len(common)} ({hit / len(common) * 100:.0f}%)")
    lines += ["", "† Partial run: the Groq free tier's 200k tokens/day quota ran out after generating the dataset. "
                  "The scored subset is listed in the JSON (`subset_ids`); per-language/macro numbers on a one-class "
                  "subset are not meaningful. Finish with `python scripts/eval_llm.py --split test` (resumable).", "",
              "### Reading these numbers honestly",
              "- The test split comes from the same generator as train, so it **over-estimates** real-world accuracy.",
              "- The hand-written challenge set is the better proxy: the small local models miss many short, "
              "conversational scams (especially in Igbo and Hausa), which is why the app uses the local model as a "
              "fast first pass and an LLM for the final verdict and explanation.",
              "- The single biggest improvement will come from **real, consented, anonymised messages** — see CONTRIBUTING.md."]
    (ROOT / "benchmark" / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
